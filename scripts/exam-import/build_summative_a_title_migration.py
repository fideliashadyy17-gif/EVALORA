"""Generate the forward migration that restores each Part B source title.

The first upload of the two First Term papers reproduced every question stem,
figure, mark and criterion but omitted the short title printed above each
constructed-response question (for example “Comparing fleet logistics
contracts”). This migration adds the title as a bold first paragraph of the
prompt document and records it in config.paper_title. It only touches questions
whose config.source is the paper's own source key, so it can never alter an
older paper.

Run: python3 scripts/exam-import/build_summative_a_title_migration.py
"""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))

import summative_a_myp4 as m4
import summative_a_myp5 as m5
from summative_b_common import plain, sql_escape

OUT = pathlib.Path(__file__).resolve().parents[2] / "supabase/migrations/20261117120000_summative_a_source_titles.sql"

PAPERS = [
    ("cb000000-0000-4000-8000-", m4.build(), m4.SOURCE),
    ("cc000000-0000-4000-8000-", m5.build(), m5.SOURCE),
]

lines = []
add = lines.append
add("-- Restore the printed Part B question titles on the two First Term papers.")
add("-- Generated by scripts/exam-import/build_summative_a_title_migration.py — do not edit by hand.")
add("--")
add("-- The initial import reproduced every stem, figure, mark and criterion but omitted the short")
add("-- printed title above each constructed-response question. This is a forward correction: no")
add("-- existing exam, question or answer is deleted and no published result is changed.")
add("--")
add("-- Only questions carrying the paper's own config.source are updated.")
add("begin;")
add("")
count = 0
for prefix, records, source in PAPERS:
    for record in records:
        title = record["cfg"].get("paper_title")
        if not title:
            continue
        question_id = prefix + str(1000 + record["n"]).zfill(12)
        prompt = plain(record["doc"])
        doc = json.dumps(record["doc"], ensure_ascii=False, separators=(",", ":"))
        add("update questions")
        add(f"   set prompt = '{sql_escape(prompt)}',")
        add(f"       prompt_doc = '{sql_escape(doc)}'::jsonb,")
        add(f"       config = config || jsonb_build_object('paper_title', '{sql_escape(title)}'),")
        add("       updated_at = now()")
        add(f" where id = '{question_id}'")
        add(f"   and config->>'source' = '{sql_escape(source)}';")
        add("")
        count += 1

add("commit;")
OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {OUT} ({OUT.stat().st_size:,} bytes, {count} questions)")
