#!/usr/bin/env python3
"""Emit the forward correction for the MYP 4 (Grade 9) matching exercise.

The applied migration ``20261117110000_myp4_grade9_first_term_summative.sql``
imported Q15–18 as four independent multiple-choice questions. The source paper
prints ONE matching exercise: a P–U formula bank and four numbered definitions,
each with a small box for one letter. The source module is corrected so a future
rebuild carries the right structure; the applied migration is never rewritten.

This script emits a NEW, idempotent migration that:

  · turns Q15 into the single parent matching question worth 4 marks,
  · gives it four typed letter fields (P–U) and the printed 2 A + 2 C split,
  · removes Q16–18 from the paper (their question rows are archived, not
    deleted, and no saved answer exists),
  · leaves every other question, mark, criterion, duration and setting alone.

    python3 scripts/exam-import/build_summative_a_matching_correction.py
"""
from __future__ import annotations

import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import summative_a_myp4 as paper  # noqa: E402
from summative_b_common import json_sql, plain  # noqa: E402

ROOT = HERE.parent.parent
OUT = ROOT / "supabase" / "migrations" / "20261118120000_myp4_q15_18_matching_exercise.sql"

QUIZ = "cb000000-0000-4000-8000-000000000001"
PARENT = "cb000000-0000-4000-8000-000000001015"
ABSORBED = [
    "cb000000-0000-4000-8000-000000001016",
    "cb000000-0000-4000-8000-000000001017",
    "cb000000-0000-4000-8000-000000001018",
]


def build_sql() -> str:
    questions = {record["n"]: record for record in paper.build()}
    matching = questions[15]
    if matching["type"] != "matching":
        raise SystemExit("the MYP 4 source module did not produce the matching exercise")
    if matching["marks"] != 4 or len(matching["cfg"]["pairs"]) != 4:
        raise SystemExit("the matching exercise must carry four one-mark pairs")
    expected = {"T", "P", "Q", "R"}
    if {pair["right"] for pair in matching["cfg"]["pairs"]} != expected:
        raise SystemExit("the matching key no longer matches the marking scheme")

    matching["cfg"]["source"] = paper.SOURCE
    # The rendered prompt shows the formula bank; the definitions are the four
    # response rows. The plain-text mirror (used by search, print fallbacks and
    # the question bank) keeps the whole exercise readable.
    fallback = plain(matching["doc"]) + "\n\n" + "\n".join(
        f"{row['number']}. {row['left']}" for row in matching["cfg"]["rows"]
    )
    record = {
        "t": matching["type"],
        "p": fallback,
        "d": matching["doc"],
        "e": matching["expl"],
        "m": matching["marks"],
        "cfg": matching["cfg"],
    }
    absorbed = ", ".join(f"'{question_id}'" for question_id in ABSORBED)
    lines = [
        "-- MYP 4 (Grade 9) Mathematics — Q15–18 as ONE matching exercise",
        "-- Generated by scripts/exam-import/build_summative_a_matching_correction.py — do not edit by hand.",
        "--",
        "-- Source: \"Grade_9_MYP_4_Mathematics_Summative_Assessment.pdf\" page 1. The paper prints a single",
        "-- formula bank P–U and four numbered definitions, each with one letter box. The original import",
        "-- split those four boxes into four independent multiple-choice questions.",
        "--",
        "-- This migration is idempotent. It updates only Q15–18 of quiz",
        f"-- {QUIZ}; every other question, mark, criterion, duration and setting is untouched.",
        "-- The absorbed question rows are archived rather than deleted so no record disappears; their",
        "-- quiz links are removed because the four boxes are now fields of the one parent question.",
        "-- The examination has no attempts or saved answers (checked before applying), so no candidate",
        "-- answer or result is migrated or lost.",
        "begin;",
        "",
        "-- 1. The one parent question: four typed letter fields, four marks, printed row criteria.",
        "update questions as target",
        "   set type = source.rec->>'t',",
        "       prompt = source.rec->>'p',",
        "       prompt_doc = source.rec->'d',",
        "       explanation = source.rec->>'e',",
        "       points = (source.rec->>'m')::numeric,",
        "       config = source.rec->'cfg',",
        "       status = 'published',",
        "       review_status = 'approved',",
        "       updated_at = now()",
        "  from (select '" + json_sql(record) + "'::jsonb as rec) as source",
        " where target.id = '" + PARENT + "';",
        "",
        "-- 2. Q15 now carries the four marks in the quiz row.",
        "update quiz_questions",
        "   set points = 4, position = 15",
        f" where quiz_id = '{QUIZ}' and question_id = '{PARENT}';",
        "",
        "-- 3. The four boxes belong to the parent question, so Q16–18 are no longer separate items.",
        "delete from quiz_questions",
        f" where quiz_id = '{QUIZ}' and question_id in ({absorbed});",
        "",
        "-- 4. Keep the absorbed rows as an audit trail instead of deleting them.",
        "update questions",
        "   set status = 'archived',",
        "       review_status = 'archived',",
        "       config = config || jsonb_build_object(",
        "         'superseded_by', '" + PARENT + "',",
        "         'superseded_reason', 'field of the Q15–18 matching exercise'",
        "       ),",
        "       updated_at = now()",
        f" where id in ({absorbed});",
        "",
        "-- 5. The examination's own instructions already say 'Matching (Q15–18) write one letter, P to U,",
        "--    in each box'; its duration, marks, criteria and eligible class are deliberately unchanged.",
        "commit;",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    sql = build_sql()
    OUT.write_text(sql, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(sql):,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
