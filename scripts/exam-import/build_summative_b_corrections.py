def question_id(prefix: str, n: int) -> str:
    return f"{prefix}{1000 + n:012d}"


def build() -> str:
    lines: list[str] = []
    add = lines.append
    add("-- Mathematics Term 1 summative audit — forward corrections")
    add("-- Generated by scripts/exam-import/build_summative_b_corrections.py.")
    add("--")
    add("-- Scope is exactly the four applied papers 0116–0119 and their own")
    add("-- examinations. No question is added, removed, renamed or re-marked, and")
    add("-- no attempt, answer, mark or historical result is touched. Every statement")
    add("-- is idempotent: replaying this migration writes the same values.")
    add("--")
    add("-- Corrections and the reason for each are recorded in")
    add("-- docs/SUMMATIVE_B_MATHS_AUDIT.md.")
    add("begin;")
    add("")

    for paper in PAPERS:
        module = importlib.import_module(paper["module"])
        questions = {q["n"]: q for q in module.build()}
        add(f"-- {paper['title']}")
        if not paper["changed"]:
            add("-- No question content defect was found in this paper.")
        for n, reason in paper["changed"].items():
            q = questions[n]
            cfg = dict(q["cfg"])
            # Keep the paper's provenance marker: the WHERE clause and the
            # per-paper queries depend on it.
            cfg["source"] = paper["source"]
            cfg["content_revision"] = REVISION
            cfg["content_revision_note"] = reason
            qid = question_id(paper["prefix"], n)
            add("")
            add(f"-- Q{n}: {reason}")
            add("update questions")
            add(f"   set type = '{q['type']}',")
            add(f"       prompt = '{sql_escape(plain(q['doc']))}',")
            add(f"       prompt_doc = '{sql_escape(json.dumps(q['doc'], ensure_ascii=False, separators=(',', ':')))}'::jsonb,")
            add(f"       explanation = '{sql_escape(q['expl'])}',")
            add(f"       config = '{sql_escape(json.dumps(cfg, ensure_ascii=False, separators=(',', ':')))}'::jsonb,")
            add("       updated_at = now()")
            add(f" where id = '{qid}'")
            add(f"   and config ->> 'source' = '{paper['source']}';")
        sheet = dict(summative_b_formulas.SHEETS[paper["exam"]])
        # The sheet is bound to its own examination, so it can never be shown on
        # another paper even if it were copied to the wrong settings row.
        sheet["exam_id"] = paper["exam"]
        add("")
        add("-- Candidate formula sheet: stored on this examination only.")
        add("update exams")
        add(f"   set settings = jsonb_set(coalesce(settings, '{{}}'::jsonb), '{{formula_sheet}}',")
        add(f"                     '{sql_escape(json.dumps(sheet, ensure_ascii=False, separators=(',', ':')))}'::jsonb, true)")
        add(f" where id = '{paper['exam']}'")
        add(f"   and title = '{sql_escape(paper['title'])}';")
        add("")

    add("commit;")
    add("")
    return "\n".join(lines)


def split_by_paper(sql: str) -> list[str]:
    """One transaction per paper: each part is independently idempotent."""
    preamble, *sections = sql.split("\n-- MYP ")
    preamble = preamble.replace("begin;", "").rstrip()
    out = []
    for index, section in enumerate(sections, start=1):
        body = "-- MYP " + section
        body = body.replace("\ncommit;", "").rstrip()
        out.append(
            f"{preamble}\n"
            f"-- Part {index} of {len(sections)} — one paper, independently idempotent.\n"
            f"begin;\n\n{body}\n\ncommit;\n"
        )
    assert len(out) == len(OUT_NAMES)
    return out


if __name__ == "__main__":
    parts = split_by_paper(build())
    for name, sql in zip(OUT_NAMES, parts):
        path = OUT_DIR / name
        path.write_text(sql, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)} ({len(sql):,} bytes)")
