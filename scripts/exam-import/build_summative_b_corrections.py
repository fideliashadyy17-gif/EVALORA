#!/usr/bin/env python3
"""Emit the forward migration that repairs the four Summative B Mathematics papers.

The four papers were applied as ``0116``–``0119``.  Their source modules are
edited so a future rebuild carries the corrections, but the applied migrations
are never rewritten: this script emits a NEW, idempotent migration that updates
only the questions that the audit found defective, plus the exam-specific
formula sheet on each examination.

    python3 scripts/exam-import/build_summative_b_corrections.py

The emitted SQL is written as four migrations (one paper each), starting at
``supabase/migrations/20261116150000_summative_b_maths_corrections_myp2.sql``.
"""
from __future__ import annotations

import importlib
import json
import pathlib
import sys

