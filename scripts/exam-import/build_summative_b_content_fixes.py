#!/usr/bin/env python3
"""Emit a forward update for repaired questions on the four Summative B papers.

Run from the repository root:

    python3 scripts/exam-import/build_summative_b_content_fixes.py

The four paper migrations (0116–0119) import with `on conflict do nothing`, so
replaying them cannot repair a question that is already live. This script emits
the SQL that rewrites the repaired rows in place instead, generated from the
same builders that produced the paper, so the database and the source of truth
cannot drift apart.

It is deliberately narrow and guarded:

  · it touches only the questions listed in REPAIRS below;
  · it refuses to run against a paper that has ever been attempted, because
    rewriting question text would reinterpret a candidate's saved response;
  · it refuses to touch a question whose option count in the database does not
    match the authored count, rather than deleting or remapping an option that
    an historical answer may reference.
"""
from __future__ import annotations

import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import summative_b_myp2 as p2  # noqa: E402
import summative_b_myp3 as p3  # noqa: E402
import summative_b_myp4 as p4  # noqa: E402
import summative_b_myp5 as p5  # noqa: E402
from summative_b_common import json_sql, plain, sql_escape  # noqa: E402

ROOT = HERE.parent.parent
OUT = ROOT / "supabase" / "migrations" / "20261115120000_summative_b_content_repairs.sql"

ORG_ID = "0a400000-0000-4000-8000-000000000001"

PAPERS = {
    "myp2": {
        "module": p2,
        "prefix": "c0700000-0000-4000-8000-",
        "quiz": "c0700000-0000-4000-8000-000000000001",
        "exam": "c0700000-0000-4000-8000-000000000002",
        "label": "MYP2-SUMMATIVE-B",
        "title": "MYP 2 (Grade 7) Mathematics — Term 1 Summative Assessment (Version B)",
    },
    "myp3": {
        "module": p3,
        "prefix": "c0800000-0000-4000-8000-",
        "quiz": "c0800000-0000-4000-8000-000000000001",
        "exam": "c0800000-0000-4000-8000-000000000002",
        "label": "MYP3-SUMMATIVE-B",
        "title": "MYP 3 (Grade 8) Mathematics — Term 1 Summative Assessment (Version B)",
    },
    "myp4": {
        "module": p4,
        "prefix": "c0900000-0000-4000-8000-",
        "quiz": "c0900000-0000-4000-8000-000000000001",
        "exam": "c0900000-0000-4000-8000-000000000002",
        "label": "MYP4-SUMMATIVE-B",
        "title": "MYP 4 (Grade 9) Mathematics — Term 1 Summative Assessment (Version B)",
    },
    "myp5": {
        "module": p5,
        "prefix": "c0a00000-0000-4000-8000-",
        "quiz": "c0a00000-0000-4000-8000-000000000001",
        "exam": "c0a00000-0000-4000-8000-000000000002",
        "label": "MYP5-SUMMATIVE-B",
        "title": "MYP 5 (Grade 10) Mathematics — Term 1 Summative Assessment (Version B)",
    },
}

# (paper, paper position) -> why it is repaired.
#
# The key is the POSITION in the paper, not the number printed on it: the MYP 5
# paper restarts its printed numbering for Part B, so both question 17 of Part A
# and the question printed 17 in Part B exist, and a repair aimed at the printed
# number would silently rewrite the healthy one.
REPAIRS = [
    ("myp2", 21, "the four option graphs were missing: the question asks which graph "
                 "shows direct proportion, so each option now carries its own figure"),
    ("myp5", 42, "a stray $ set a whole clause as an equation, and a second one printed "
                 "as a currency symbol in part (b)"),
    ("myp5", 44, "a stray $ printed as a currency symbol in the stem"),
]


def record(paper_key: str, position: int):
    module = PAPERS[paper_key]["module"]
    for item in module.build():
        if item["n"] == position:
            return item
    raise SystemExit(f"{paper_key}: no question at position {position}")


def question_id(paper_key: str, item: dict) -> str:
    return f"{PAPERS[paper_key]['prefix']}{1000 + item['n']:012d}"


def main() -> None:
    lines: list[str] = []
    add = lines.append

    add("-- Summative B (Version B) — safe forward update of repaired questions.")
    add("-- Generated by scripts/exam-import/build_summative_b_content_fixes.py; do not edit.")
    add("--")
    add("-- The four paper migrations import with ON CONFLICT DO NOTHING, so they cannot")
    add("-- repair a question that is already live. This file rewrites the repaired rows")
    add("-- in place, preserving every UUID, and fails closed rather than rewriting a")
    add("-- paper that has been attempted or an option set it does not recognise.")
    add("--")
    for paper_key, position, why in REPAIRS:
        item = record(paper_key, position)
        printed = item["cfg"].get("question_number", item["n"])
        add(f"--   {PAPERS[paper_key]['label']} position {position} (printed question {printed}): {why}")
    add("")
    add("begin;")
    add("set local lock_timeout = '5s';")
    add("set local statement_timeout = '90s';")
    add("")

    # A paper-level guard: the questions below are only safe to rewrite while no
    # candidate has answered them.
    for paper_key in sorted({key for key, _, _ in REPAIRS}):
        paper = PAPERS[paper_key]
        add(f"-- {paper['label']}: the paper must exist, belong to this tenant, and be unattempted.")
        add("do $$")
        add("declare")
        add("  v_attempts integer;")
        add("begin")
        add("  perform 1 from public.exams")
        add(f"   where id = '{paper['exam']}'::uuid and organization_id = '{ORG_ID}'::uuid")
        add("   for update;")
        add("  if not found then")
        add(f"    raise exception '{paper['label']}: the fixed examination row is missing or belongs to another tenant';")
        add("  end if;")
        add("  perform 1 from public.quizzes")
        add(f"   where id = '{paper['quiz']}'::uuid and organization_id = '{ORG_ID}'::uuid")
        add("   for update;")
        add("  if not found then")
        add(f"    raise exception '{paper['label']}: the fixed quiz row is missing or belongs to another tenant';")
        add("  end if;")
        add("  select count(*) into v_attempts from public.exam_attempts")
        add(f"   where exam_id = '{paper['exam']}'::uuid;")
        add("  if v_attempts <> 0 then")
        add(f"    raise exception '{paper['label']}: refusing to rewrite a paper with % attempt(s)', v_attempts;")
        add("  end if;")
        add("end $$;")
        add("")

    # Question content: prompt, prompt_doc and the worked marking solution.
    add("-- The repaired question content itself.")
    add("create temporary table _summative_b_repair (")
    add("  question_id uuid primary key,")
    add("  prompt text not null,")
    add("  prompt_doc jsonb not null,")
    add("  explanation text not null,")
    add("  option_count integer not null")
    add(") on commit drop;")
    add("")
    rows = []
    seen = set()
    for paper_key, position, _why in REPAIRS:
        item = record(paper_key, position)
        if question_id(paper_key, item) in seen:
            raise SystemExit(f"{paper_key}: position {position} resolves to a question already repaired")
        seen.add(question_id(paper_key, item))
        rows.append({
            "q": question_id(paper_key, item),
            "p": plain(item["doc"]),
            "d": item["doc"],
            "e": item["expl"],
            "o": len(item.get("options") or []),
        })
    add("insert into _summative_b_repair (question_id, prompt, prompt_doc, explanation, option_count)")
    add("select (x->>'q')::uuid, x->>'p', x->'d', x->>'e', (x->>'o')::integer")
    add("  from jsonb_array_elements('" + json_sql(rows) + "'::jsonb) as x;")
    add("")
    add("do $$")
    add("declare")
    add("  v_found integer;")
    add("  v_options integer;")
    add("  v_expected integer;")
    add("begin")
    add("  select count(*) into v_found")
    add("    from _summative_b_repair r")
    add("    join public.questions q on q.id = r.question_id")
    add(f"     and q.organization_id = '{ORG_ID}'::uuid;")
    add(f"  if v_found <> {len(rows)} then")
    add("    raise exception 'summative B repair: found % of the expected "
        + str(len(rows))
        + " question rows', v_found;")
    add("  end if;")
    add("")
    add("  -- Every option row that exists must be one the paper still authors, so an")
    add("  -- update can rewrite it in place instead of deleting anything.")
    add("  for v_expected, v_options in")
    add("    select r.option_count, count(o.id)")
    add("      from _summative_b_repair r")
    add("      left join public.question_options o on o.question_id = r.question_id")
    add("     group by r.question_id, r.option_count")
    add("  loop")
    add("    if v_expected <> v_options then")
    add("      raise exception 'summative B repair: a question authors % option(s) but the database has %; "
        "refusing to remap them', v_expected, v_options;")
    add("    end if;")
    add("  end loop;")
    add("end $$;")
    add("")
    add("update public.questions q")
    add("   set prompt = r.prompt,")
    add("       prompt_doc = r.prompt_doc,")
    add("       explanation = r.explanation")
    add("  from _summative_b_repair r")
    add(" where q.id = r.question_id")
    add(f"   and q.organization_id = '{ORG_ID}'::uuid;")
    add("")

    # Option documents, including the graphs restored on MYP2 Q21.
    option_rows = []
    for paper_key, position_in_paper, _why in REPAIRS:
        item = record(paper_key, position_in_paper)
        for position, option in enumerate(item.get("options") or []):
            option_rows.append({
                "q": question_id(paper_key, item),
                "p": position,
                "d": {
                    "type": "doc",
                    "content": (
                        [{"type": "paragraph", "content": _inline(option["body"])}]
                        + ([option["figure"]] if option.get("figure") else [])
                    ),
                },
            })

    if option_rows:
        add("-- The printed options, including any figure an option carries.")
        add("update public.question_options o")
        add("   set content_doc = v.doc")
        add("  from (")
        add("    select (x->>'q')::uuid as question_id, (x->>'p')::integer as position, x->'d' as doc")
        add("      from jsonb_array_elements('" + json_sql(option_rows) + "'::jsonb) as x")
        add("  ) as v")
        add(" where o.question_id = v.question_id and o.position = v.position;")
        add("")

    add("-- Nothing is deleted and no UUID is reassigned, so a replay changes nothing.")
    add("commit;")

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}  ({len(lines)} lines, "
          f"{len(rows)} questions, {len(option_rows)} options)")


def _inline(text: str):
    """Mirror of summative_b_common._inline, so option documents match the import."""
    import re

    from summative_b_common import _MATH_SPLIT  # noqa: PLC0415

    out = []
    for part in _MATH_SPLIT.split(text):
        if not part:
            continue
        if part.startswith("$") and part.endswith("$") and len(part) > 2:
            out.append({"type": "mathInline", "attrs": {"latex": part[1:-1]}})
        else:
            out.append({"type": "text", "text": part})
    return out or [{"type": "text", "text": ""}]


if __name__ == "__main__":
    main()
