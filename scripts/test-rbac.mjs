await check('dashboard.view',false);
await db.exec(`update access_permission_overrides set granted=true; update access_role_permissions set granted=false where role_id=(select id from access_roles where slug='school_founder') and permission_id=(select id from access_permissions where key='dashboard.view');`);
await check('dashboard.view',false);
await db.exec('delete from access_permission_overrides; update access_role_permissions set granted=true; update access_roles set is_active=false where slug=\'school_founder\';');
await check('dashboard.view',false);
await db.exec("update access_roles set is_active=true where slug='school_founder'; update organization_members set status='suspended';");
await check('dashboard.view',false);
await db.exec("update organization_members set status='active'; update profiles set status='suspended';");
