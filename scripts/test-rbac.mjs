await assert.rejects(()=>db.exec(`insert into exams(id,organization_id,title) values(gen_random_uuid(),'${org}','DENIED')`),/row-level security/);checks++;
await assert.rejects(()=>db.exec("insert into access_roles(name,slug) values('Abuse','abuse')"),/row-level security/);checks++;
assert.equal((await db.query('select * from access_audit_events')).rows.length,0);checks++;
await assert.rejects(()=>db.query("insert into access_audit_events(action,entity) values('FAKE','exams')"),/permission denied|row-level security/);checks++;
