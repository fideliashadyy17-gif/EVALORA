#!/usr/bin/env node
/**
 * Emit the migration that seeds the automatic-marking rubrics.
 *
 * Run from the repository root:
 *
 *     node scripts/build-summative-b-rubric-migration.mjs
 *
 * `src/lib/marking/summativeBRubrics.json` is the single source of truth: the
 * marking engine compiles it into the built-in rubrics, and this script writes
 * the same definitions into `questions.config.auto_marking` so a teacher can
 * read and adjust a question's rubric in the authoring form instead of it being
 * invisible in the database.
 *
 * The emitted SQL is a single guarded, idempotent `jsonb_set` per question. It
 * never deletes and never renumbers, and it refuses to run unless it finds
 * every one of the 65 constructed responses it expects.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const SOURCE = path.join(ROOT, "src/lib/marking/summativeBRubrics.json");
const OUT = path.join(ROOT, "supabase/migrations/0122_summative_b_auto_marking.sql");

const ORG_ID = "0a400000-0000-4000-8000-000000000001";

const raw = JSON.parse(readFileSync(SOURCE, "utf8"));
const entries = Object.entries(raw)
  .filter(([id]) => !id.startsWith("_"))
  .map(([id, rubric]) => {
    if (!/^[0-9a-f-]{36}$/.test(id)) throw new Error(`not a question id: ${id}`);
    const total = (rubric.parts ?? []).reduce((sum, part) => sum + Number(part.marks ?? 0), 0);
    if (total !== Number(rubric.total)) {
      throw new Error(`${id}: parts add up to ${total}, rubric says ${rubric.total}`);
    }
    return { id, rubric };
  })
  .sort((a, b) => (a.id < b.id ? -1 : 1));

if (entries.length !== 65) throw new Error(`expected 65 rubrics, found ${entries.length}`);

const lines = [];
const add = lines.push.bind(lines);

add("-- MYP Mathematics Summative B — automatic-marking rubrics.");
add("-- Generated by scripts/build-summative-b-rubric-migration.mjs — do not edit by hand.");
add("--");
add("-- Source of truth: src/lib/marking/summativeBRubrics.json. The engine already");
add("-- compiles those definitions into its built-in rubrics; writing them here as well");
add("-- is what makes a question's rubric visible and editable in the authoring form.");
add("--");
add("-- Every statement is a guarded jsonb_set on one fixed question row: replaying the");
add("-- migration overwrites the rubric with the same definition and changes nothing else.");
add("");
add("begin;");
add("set local lock_timeout = '5s';");
add("set local statement_timeout = '90s';");
add("");
add("do $$");
add("declare");
add("  v_found integer;");
add("begin");
add("  select count(*) into v_found");
add("    from public.questions q");
add("    join public.quiz_questions qq on qq.question_id = q.id");
add("   where q.type = 'open_ended'");
add(`     and q.organization_id = '${ORG_ID}'::uuid`);
add(`     and qq.quiz_id in (`);
for (const quiz of [
  "c0700000-0000-4000-8000-000000000001",
  "c0800000-0000-4000-8000-000000000001",
  "c0900000-0000-4000-8000-000000000001",
  "c0a00000-0000-4000-8000-000000000001",
]) add(`       '${quiz}'::uuid,`);
add("       '00000000-0000-4000-8000-000000000000'::uuid  -- keeps the list comma-separated");
add("     );");
add(`  if v_found <> ${entries.length} then`);
add(`    raise exception 'summative B rubrics: found % of the expected ${entries.length} constructed responses', v_found;`);
add("  end if;");
add("end $$;");
add("");

for (const { id, rubric } of entries) {
  const json = JSON.stringify(rubric).replace(/'/g, "''");
  add(`-- ${rubric.total} mark(s), criterion ${rubric.criterion}`);
  add("update public.questions");
  add("   set config = jsonb_set(coalesce(config, '{}'::jsonb), '{auto_marking}',");
  add(`                         '${json}'::jsonb, true)`);
  add(` where id = '${id}'::uuid`);
  add(`   and organization_id = '${ORG_ID}'::uuid`);
  add(`   and type = 'open_ended';`);
  add("");
}

add("commit;");

writeFileSync(OUT, lines.join("\n"), "utf8");
console.log(`wrote ${path.relative(ROOT, OUT)}  (${entries.length} rubrics, ${lines.length} lines)`);
