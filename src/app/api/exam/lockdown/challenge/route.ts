import { NextResponse } from "next/server";

/**
 * This endpoint used to mint a fully valid HMAC attestation for any request
 * that supplied a forgeable User-Agent or x-evalora-secure-browser header.
 * That turned the challenge endpoint into an attestation oracle. Attestations
 * must now be produced by the Secure Browser's isolated desktop process and
 * are verified by the admission routes; a web request must never mint one.
 */
function rejectWebMintedAttestation() {
  return NextResponse.json(
    {
      error: "Attestations must be generated by the EVALORA Secure Exam Browser. This web attestation endpoint is retired.",
    },
    { status: 410, headers: { "Cache-Control": "no-store" } },
  );
}

export async function GET() {
  return rejectWebMintedAttestation();
}

export async function POST() {
  return rejectWebMintedAttestation();
}
